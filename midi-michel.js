await loadScript('https://6120.eu/public/midi.js')
baseUrl = 'https://6120.eu/public/michel.jpg?'
x = 3
setResolution(1024 * x, 1024 * x)
s0.initImage(baseUrl)
await midi.start()
	.show()
// Norns note range: 48–60
// note(N) triggers ADSR on specific MIDI note N
// .range(min, max) remaps envelope [0,1] → [min,max]
// .scale(f) multiplies envelope output by f
lead = midi.input('*')
	.channel(0)
pad = midi.input('*')
	.channel(1)
bass = midi.input('*')
	.channel(2)
kick = midi.input('*')
	.channel(3)
snare = midi.input('*')
	.channel(4)
hh = midi.input('*')
	.channel(5)
lead2 = midi.input('*')
	.channel(6)
pad2 = midi.input('*')
	.channel(7)


solid()
	.add(src(s0))
	.scale(hh.note('*')
		.adsr(0, 100, 1, 250)
		.range(1, 2))
	.pixelate(lead.note('*')
		.adsr(100, 200, 4, 150)
		.range(-200.05, 500.05), lead2.note('*')
		.adsr(100, 200, 4, 150)
		.range(-200.05, 500.05))
	.mult(solid(1, 0, .75), kick.note('*')
		.adsr(180, 200, 3, 100)
		.range(.2, .7))
	.blend(o0, .7)
	.add(shape(20, .05)
		.scroll([.1, -.15], -0.02)
		.add(shape(20, .05)
			.scroll([-.1, .15], -0.02))
        .mult(solid([0,1],[0,1],[1,0,0])))
	.out(o0)
src(o0)
	.out(o1)
src(o0)
	.diff(o1)
	.blend(src(o1)
		.add(o2), .4)
	.out(o2)
render(o2)
